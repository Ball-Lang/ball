"""Regenerate ``compiled_cli.py`` from the self-hosted Ball CLI core.

The Python half of the cli-core adoption (issue #570), mirroring
``ball_engine.regen`` / ``go/cli/cmd/regen`` / ``rust/cli/tool`` /
``csharp/cli/tool``: read the portable CLI verbs' Ball encoding
(``dart/self_host/cli.ball.json``, a gitignored artifact of ``dart run
compiler/tool/gen_cli_json.dart``), compile it through ``ball_compiler`` in
**library mode** (``cli_core`` has no runnable entry point — its public surface
is the ``infoReport``/``validateReport``/``treeReport``/``versionLine`` report
functions), and write the module with a NEVER-EDIT header.

``compiled_cli.py`` is a GENERATED, gitignored build artifact — to change it, fix
``dart/shared/lib/cli_core.dart`` (then rerun ``gen_cli_json.dart``) or
``python/compiler``, and rerun this. It is never shipped in the ``ball-lang``
wheel: an installed wheel carries the Ball SOURCE and compiles it on first use
(:mod:`ball_cli.bootstrap_clicore`), the same rule the engine follows.

Usage:  python -m ball_cli.regen
"""

from __future__ import annotations

import sys
from pathlib import Path

_HERE = Path(__file__).resolve()


def _repo_root() -> Path:
    d = _HERE.parent
    while d != d.parent:
        if (d / "proto" / "ball" / "v1" / "ball.proto").exists():
            return d
        d = d.parent
    raise SystemExit("[regen-cli] not inside the ball repo (no proto/ball/v1/ball.proto)")


HEADER = (
    "# Code generated by `python -m ball_cli.regen` from "
    "dart/self_host/cli.ball.json.\n"
    "# DO NOT EDIT BY HAND. This is the self-hosted Ball CLI core (the info/\n"
    "# validate/tree/version report functions), compiled from\n"
    "# dart/shared/lib/cli_core.dart's own Ball encoding through the Ball -> Python\n"
    "# compiler. To change it, fix dart/shared/lib/cli_core.dart (then rerun\n"
    "# gen_cli_json.dart) or python/compiler, and rerun the regenerator. See\n"
    "# python/cli/AGENTS.md.\n\n"
)


def main() -> int:
    root = _repo_root()
    # Import the sibling compiler + runtime by path (the packages are isolated).
    sys.path.insert(0, str(root / "python" / "compiler"))
    sys.path.insert(0, str(root / "python" / "runtime"))
    from ball_compiler.compiler import compile_library
    from ball_compiler.loader import load_program

    json_path = root / "dart" / "self_host" / "cli.ball.json"
    if not json_path.exists():
        raise SystemExit(
            f"[regen-cli] {json_path} is missing; regenerate the self-host source first:\n"
            f"            cd dart && dart run compiler/tool/gen_cli_json.dart"
        )

    print(f"[regen-cli] loading {json_path}", file=sys.stderr)
    program = load_program(json_path)
    modules = program.get("modules", [])
    print(
        f"[regen-cli] compiling program {program.get('name', '')!r} "
        f"v{program.get('version', '')} ({len(modules)} modules)",
        file=sys.stderr,
    )

    src = compile_library(program)
    out_path = _HERE.parent / "compiled_cli.py"
    out_path.write_text(HEADER + src, encoding="utf-8")
    print(f"[regen-cli] wrote {out_path} ({len(HEADER) + len(src)} bytes)", file=sys.stderr)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
