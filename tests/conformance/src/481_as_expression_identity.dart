// `value as T` (the EXPRESSION, not the cast PATTERN #641 already pins) is an
// UNCHECKED identity on every target's reference implementation: the Dart
// reference engine's own `std.as` dispatch (`dart/engine/lib/engine_std.dart`,
// `'as': _extractUnaryArg`), Python's `ballrt.selfhost.as_type`, Go's
// `ballrt.AsType`, C#'s `BallStd.AsType` and TypeScript's/C++'s identity arms
// all just hand the value back unchanged, never inspecting the runtime type —
// but Rust's compiled `ball_as` used to PANIC on a mismatch, an UNCATCHABLE
// process abort no other target produces (issue #707).
//
// The real Dart SDK's `as` genuinely IS a checked runtime cast, so a bare
// mismatched `5 as String` would crash the golden-generation step; `describeAs`
// wraps it in a `try`/`catch` so the fixture's golden (generated by running
// THIS source on the SDK) matches every Ball engine's computed result: the
// SDK throws and the catch body prints the original value, and the Ball-level
// identity cast's result, which is still just the original value, prints the
// same text through string interpolation — interpolation never inspects the
// declared static type, only the runtime value, so both paths agree.

String describeAs(dynamic value) {
  try {
    final dynamic casted = value as String;
    return 'ok:$casted';
  } catch (_) {
    return 'ok:$value';
  }
}

void main() {
  print(describeAs('hello'));
  print(describeAs(5));
  print(describeAs(3.5));
}
