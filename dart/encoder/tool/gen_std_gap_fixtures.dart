Map<String, dynamic> letStmt(
  String name,
  Map<String, dynamic> value, {
  String keyword = 'var',
}) {
  return {
    'let': {
      'name': name,
      'value': value,
      'metadata': {'keyword': keyword},
    },
  };
}

Map<String, dynamic> mainFn(List<Map<String, dynamic>> statements) {
  return {
    'name': 'main',
    'outputType': 'void',
    'body': {
      'block': {'statements': statements},
    },
    'metadata': {'kind': 'function'},
  };
}

