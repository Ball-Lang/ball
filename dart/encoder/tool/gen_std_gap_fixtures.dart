/// `std_collections.list_find(list, callback)` — the callback goes under the
/// name `ListCallbackInput` actually declares (`callback`); every target
/// aliases `callback`/`function`/`value`, so this is the canonical spelling.
Map<String, dynamic> listFind(
  Map<String, dynamic> list,
  Map<String, dynamic> callback,
) => collectionsCall(
  'list_find',
  msg([field('list', list), field('callback', callback)]),
);

/// `std.try(body, catches)` where each catch entry is `(type, variable, body)`.
/// A `type` of `''` means an untyped `catch (e)`.
Map<String, dynamic> tryCatch(
  List<Map<String, dynamic>> bodyStatements,
  List<({String type, String variable, Map<String, dynamic> body})> catches,
) => stdCall(
  'try',
  msg([
    field('body', {
      'block': {'statements': bodyStatements},
    }),
    field(
      'catches',
      listLit([
        for (final c in catches)
          msg([
            if (c.type.isNotEmpty) field('type', literal(c.type)),
            field('variable', literal(c.variable)),
            field('body', {
              'block': {
                'statements': [stmt(c.body)],
              },
            }),
          ]),
      ]),
    ),
  ]),
);

/// Builds a minimal single-module Program: a `std` module carrying exactly
/// the base functions used (mirrors the minimal footprint the encoder itself
/// would produce, and the hand-authored `188_std_time_now` fixture).
Map<String, dynamic> buildProgramJson({
  required String name,
  required List<Map<String, Object?>> stdFunctions,
  required List<Map<String, Object?>> stdTypeDefs,
  required Map<String, dynamic> mainFunction,
  List<Map<String, Object?>> extraModules = const [],
}) {
  return {
    'name': name,
    'version': '1.0.0',
    'modules': [
      {'name': 'std', 'functions': stdFunctions, 'typeDefs': stdTypeDefs},
      ...extraModules,
      {
        'name': 'main',
        'functions': [mainFunction],
      },
    ],
    'entryModule': 'main',
    'entryFunction': 'main',
  };
}

Future<void> writeFixture(
  String id,
  Map<String, dynamic> programJson, {
  bool expectOutput = true,
}) async {
  final program = Program()..mergeFromProto3Json(programJson);
  final jsonMap = encodeBallFileJson(program);
  final jsonStr = const JsonEncoder.withIndent('  ').convert(jsonMap);
  final outDir = '../../tests/conformance';
  File('$outDir/$id.ball.json').writeAsStringSync('$jsonStr\n');

  if (expectOutput) {
    final lines = <String>[];
    await BallEngine(program, stdout: lines.add).run();
    File(
      '$outDir/$id.expected_output.txt',
    ).writeAsStringSync('${lines.join('\n')}\n');
  }
  stderr.writeln(
    'Wrote $id.ball.json${expectOutput ? ' + expected_output.txt' : ''}',
  );
}

