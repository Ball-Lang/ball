/// The real RED-capable proof issue #707 needs: `5 as String` with **no**
/// enclosing `try` anywhere in the compiled program, so a panicking
/// `ball_as` has no `catch_unwind` to be caught by and propagates straight
/// out of `fn main()` — an uncaught panic that unwinds through `main` and
/// makes the process exit non-zero (Rust's default panic behavior), not
/// merely a wrong line of stdout. `as_expression_on_a_mismatched_runtime_type_never_panics`
/// above cannot tell this case apart from the pre-fix panic (see the module
/// doc comment); this test can, because here the panic has nothing to catch
/// it at all.
///
/// RED before the fix: the compiled binary panicked with no handler
/// anywhere in `main`'s call chain, printed Rust's own
/// `thread 'main' panicked at ...` to stderr, and exited with a non-zero
/// code (101) instead of running `compile_and_run`'s success path at all —
/// `compile_and_run` itself turns that into a test failure, dumping the
/// panic's stderr.
#[test]
fn as_on_a_mismatched_type_never_panics_with_no_enclosing_try() {
    let program = load_program_from_json(AS_WITH_NO_ENCLOSING_TRY);
    let compiled = Compiler::new(&program).compile();
    assert!(
        !compiled.contains("catch_unwind"),
        "this test is only meaningful while the compiled program has no `try`-wrapped \
         `catch_unwind` anywhere for a panic to be caught by — if a `try` crept in, this test \
         no longer proves anything about an UNCAUGHT panic:\n{compiled}"
    );
    let stdout = compile_and_run("as_with_no_enclosing_try", &compiled);
    assert_eq!(
        stdout, "5\n",
        "`value as T` must be an unchecked identity even with no enclosing `try` to catch a \
         panic — the mismatched 5 as String must print through as 5, not abort the process"
    );
}
